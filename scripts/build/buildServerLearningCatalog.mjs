import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const server = await createServer({ root, appType: 'custom', logLevel: 'error', server: { middlewareMode: true, hmr: false } });
try {
  const loader = await server.ssrLoadModule('/src/data/index.ts');
  const catalog = {};
  const courses = { grade9: ['math', 'english'], grade10: ['math','english','physics','chemistry','biology','history'], grade11: ['math','english','physics','chemistry','biology'] };
  const keys = ['id','subjectId','topicId','questionTypeId','correctAnswer','acceptedAnswers','correctFinalAnswer','acceptedFinalAnswers','answerSchema','validatorType'];
  for (const [grade, subjects] of Object.entries(courses)) for (const subject of subjects) {
    const data = await loader.loadSubjectData(grade, subject);
    for (const q of data.questions) {
      const item = Object.fromEntries(keys.filter(key => q[key] !== undefined).map(key => [key,q[key]]));
      if (q.options) item.options = ['A','B','C','D'];
      if (catalog[q.id] && JSON.stringify(catalog[q.id]) !== JSON.stringify(item)) throw new Error(`Conflicting question ID: ${q.id}`);
      catalog[q.id] = item;
    }
  }
  // Mobile starter questions have independent IDs; never map them to unrelated web items.
  const { QUESTION_BANK } = await server.ssrLoadModule('/mobile/services/questionBank.ts');
  for (const [topicId, questions] of Object.entries(QUESTION_BANK)) for (const q of questions) {
    if (q.topicId !== topicId || !/^[A-D]$/.test(q.correctAnswer) || !q.subjectId) {
      throw new Error(`Invalid mobile question: ${q.id}`);
    }
    const id = `mobile-v1-${q.id}`;
    if (catalog[id]) throw new Error(`Conflicting mobile question ID: ${id}`);
    catalog[id] = {
      id, subjectId: q.subjectId, topicId: q.topicId,
      questionTypeId: `mobile-v1-${q.topicId}`, correctAnswer: q.correctAnswer,
      options: ['A', 'B', 'C', 'D'], validatorType: 'choice',
    };
  }
  const contentDir = path.join(root,'functions/content');
  const generatedDir = path.join(root,'functions/src/generated');
  fs.mkdirSync(contentDir,{recursive:true}); fs.mkdirSync(generatedDir,{recursive:true});
  fs.writeFileSync(path.join(contentDir,'answer-catalog.json'),JSON.stringify(catalog));
  const types = fs.readFileSync(path.join(root, 'src/types/index.ts'), 'utf8').replaceAll("'./roadmapContract'", "'./roadmapContract.js'");
  fs.writeFileSync(path.join(generatedDir, 'types.ts'), types);
  fs.writeFileSync(path.join(generatedDir, 'roadmapContract.ts'), fs.readFileSync(path.join(root, 'src/types/roadmapContract.ts'), 'utf8').replaceAll("'./index'", "'./types.js'"));
  for (const name of ['answerValidator','theme','premium']) {
    const source = fs.readFileSync(path.join(root,`src/utils/${name}.ts`),'utf8').replaceAll("'../types'", "'./types.js'");
    fs.writeFileSync(path.join(generatedDir,`${name}.ts`),'// Generated by scripts/build/buildServerLearningCatalog.mjs; do not edit.\n'+source);
  }
  console.log(`Server answer catalog: ${Object.keys(catalog).length} questions.`);
} finally { await server.close(); }
